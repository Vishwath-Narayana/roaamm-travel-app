// Generates the CSS linear() spring easing used as --ease-spring.
//
// A damped spring (damping ratio 0.72) sampled over its settle time and
// written as linear() points: a gentle single overshoot of about 4% and an
// almost invisible undershoot, then rest. Run it after changing the spring:
//
//   node scripts/gen-spring.mjs
//
// It rewrites packages/design-tokens/spring.gen.ts; the @supports block in
// apps/web/src/styles/tokens.css must carry the same string (a test checks).

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const OUT = join(ROOT, "packages/design-tokens/spring.gen.ts");

const ZETA = 0.72; // damping ratio: < 1 overshoots once, gently
const SAMPLES = 100; // points before simplification
const TOLERANCE = 0.0015; // drop points this close to a straight line

/** Position of a unit step response of an under-damped spring at time t (omega = 1). */
function spring(t) {
  const wd = Math.sqrt(1 - ZETA * ZETA);
  return 1 - Math.exp(-ZETA * t) * (Math.cos(wd * t) + (ZETA / wd) * Math.sin(wd * t));
}

// Settle time: the last moment the curve is more than 0.1% away from 1.
let end = 0;
for (let t = 0; t < 40; t += 0.01) if (Math.abs(spring(t) - 1) > 0.001) end = t;

const points = Array.from({ length: SAMPLES + 1 }, (_, i) => {
  const x = i / SAMPLES;
  return { x, y: i === SAMPLES ? 1 : spring(x * end) };
});

// Ramer-Douglas-Peucker: keep the fewest points such that every dropped
// point lies within TOLERANCE of the straight line that replaces it.
function simplify(pts) {
  if (pts.length < 3) return pts;
  const [a, c] = [pts[0], pts[pts.length - 1]];
  let worst = 0;
  let index = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const b = pts[i];
    const d = Math.abs(b.y - (a.y + ((c.y - a.y) * (b.x - a.x)) / (c.x - a.x)));
    if (d > worst) [worst, index] = [d, i];
  }
  if (worst <= TOLERANCE) return [a, c];
  return [...simplify(pts.slice(0, index + 1)).slice(0, -1), ...simplify(pts.slice(index))];
}
const kept = simplify(points);

const fmt = (n) => String(Math.round(n * 1000) / 1000);
const value = `linear(${kept.map((p, i) => (i === 0 || i === kept.length - 1 ? fmt(p.y) : `${fmt(p.y)} ${fmt(p.x * 100)}%`)).join(", ")})`;
const overshoot = Math.max(...points.map((p) => p.y)) - 1;

writeFileSync(
  OUT,
  `// Generated by scripts/gen-spring.mjs (damping ratio ${ZETA}). Do not edit by hand.\n` +
    `// Peak overshoot: ${(overshoot * 100).toFixed(1)}%.\n` +
    `export const SPRING_LINEAR =\n  "${value}";\n`,
);
console.log(`${kept.length} points, overshoot ${(overshoot * 100).toFixed(1)}%`);
console.log(value);
